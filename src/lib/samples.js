export function monthlySamples(anchor, firstId = 8) {
  const month = new Date(anchor);
  const lastDay = new Date(month.getFullYear(), month.getMonth() + 1, 0).getDate();
  return schedule.filter(([day]) => day <= lastDay).map(([day, t, g, p], index) => {
    const due = +new Date(month.getFullYear(), month.getMonth(), day);
    const done = due < anchor && index % 5 === 0;
    return { id: firstId + index, t, g, p, due, done, ...(done ? { at: due + 12 * 3600e3 } : {}) };
  });
}
